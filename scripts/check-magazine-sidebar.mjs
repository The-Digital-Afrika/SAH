import assert from 'node:assert/strict';
const tabs = await (await fetch('http://localhost:9231/json')).json();
const tab = tabs.find(tab => tab.type === 'page');
const socket = new WebSocket(tab.webSocketDebuggerUrl);
await new Promise(resolve => socket.addEventListener('open', resolve, { once: true }));
let id = 0;
const pending = new Map();
socket.addEventListener('message', event => { const data = JSON.parse(event.data); if (pending.has(data.id)) { pending.get(data.id)(data); pending.delete(data.id); } });
const call = (method, params = {}) => new Promise(resolve => { const next = ++id; pending.set(next, resolve); socket.send(JSON.stringify({ id: next, method, params })); });
await call('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
await new Promise(resolve => setTimeout(resolve, 1000));
const response = await call('Runtime.evaluate', { returnByValue: true, expression: `(() => {
 const sidebar = document.querySelector('[data-independent-scroll]');
 if (!sidebar) return { error: 'Magazine sidebar missing' };
 const before = scrollY;
 sidebar.scrollTop = 500;
 return { height: sidebar.clientHeight, width: sidebar.clientWidth, scrollHeight: sidebar.scrollHeight, scrollTop: sidebar.scrollTop, pageStayed: before === scrollY, overflow: getComputedStyle(sidebar).overflowY, viewport: innerHeight, horizontalOverflow: document.documentElement.scrollWidth > innerWidth, count: sidebar.querySelectorAll('[data-ad-format]').length };
})()` });
const result = response.result.result.value;
console.log(JSON.stringify(result));
socket.close();
assert.equal(result.error, undefined);
assert.equal(result.count, 12);
assert.equal(result.overflow, 'auto');
assert.equal(result.pageStayed, true);
assert.equal(result.horizontalOverflow, false);
assert.equal(result.scrollTop, 500);
assert.ok(result.width >= 300);
assert.ok(result.height < result.viewport);
assert.ok(result.scrollHeight > result.height);
